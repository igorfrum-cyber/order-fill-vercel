import assert from "node:assert/strict";
import path from "node:path";
import { readFile } from "node:fs/promises";
import { read, utils } from "xlsx";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("dialog", async (dialog) => { errors.push(dialog.message()); await dialog.dismiss(); });
  await page.goto(process.env.TEST_URL || "http://127.0.0.1:3201/");
  await page.locator("#warehouseModeButton").click();
  await page.locator("#warehouseBrand").selectOption("skin_synergy");
  await page.locator("#officeTransferFile").setInputFiles(path.resolve("test-output/tyumen/Офис Тюмень.xlsx"));
  await page.locator("#warehouseTransferFile").setInputFiles(path.resolve("test-output/tyumen/Склад Тюмень.xlsx"));
  await page.locator("#warehouseForm button").click();
  await page.locator("#warehouseResult:not(.hidden)").waitFor();
  assert.equal(await page.locator("#warehouseRows tr").count(), 4);
  assert.equal(await page.locator("#warehouseRows input").first().inputValue(), "15");
  await page.locator("#warehouseRows input").first().fill("20");
  assert.equal(await page.locator("[data-office-after]").first().innerText(), "30");
  await page.screenshot({ path: "test-output/tyumen/desktop.png", fullPage: true });
  const downloadPromise = page.waitForEvent("download");
  await page.locator("#warehouseDownload").click();
  const download = await downloadPromise;
  await download.saveAs("test-output/tyumen/transfer.xlsx");
  const exported = read(await readFile("test-output/tyumen/transfer.xlsx"), { type: "buffer" });
  const rows = utils.sheet_to_json(exported.Sheets.Лист_1, { header: 1 });
  assert.equal(rows[6][3], "СКЛАД ДОСТАВКА");
  assert.equal(rows[6][5], "Склад Тюмень");
  assert.equal(rows[10][3], 20);
  await page.locator("#warehouseRows input").first().fill("91");
  assert.equal(await page.locator("#warehouseRows input").first().evaluate((el) => el.checkValidity()), false);
  await page.locator("#warehouseRows input").first().fill("20");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "test-output/tyumen/mobile.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, "Page must not overflow horizontally");
  await page.locator("#orderModeButton").click();
  await page.locator("#twoTyumenSources").check();
  assert.equal(await page.locator("#warehouseSourceField").isVisible(), true);
  assert.equal(await page.locator("#warehouseSection").isVisible(), false);
  await page.locator("#northModeButton").click();
  await page.locator("#northTwoSources").check();
  assert.equal(await page.locator("#northWarehouseField").isVisible(), true);
  assert.deepEqual(errors, []);
  console.log("Desktop/mobile UI, manual edits, stock limits, exported 1C transfer: passed");
} finally { await browser.close(); }
